import {filterMeetings} from './meeting-filters.ts';
import {draftValid,type MeetingDraft} from './chat-result.ts';
import type {Meeting} from './meetings.ts';
export type Proposal={kind:'cancel'|'reschedule';meetings:Meeting[];draft?:MeetingDraft};
const label=(m:Meeting)=>`«${m.draft.title}» — ${m.draft.date} ساعت ${m.draft.time}`;
export function conversationResult(content:string,meetings:Meeting[]){
 const p=JSON.parse(content.replace(/^```(?:json)?\s*/i,'').replace(/\s*```$/,''));
 const active=meetings.filter(m=>m.status==='active');
 const selected=active.filter(m=>Array.isArray(p.ids)&&p.ids.includes(m.id));
 if(p.intent==='list'){
  const filter=['all','upcoming','past','cancelled'].includes(p.filter)?p.filter:'all';
  const rows=filterMeetings(meetings,typeof p.query==='string'?p.query.slice(0,100):'',filter);
  return {reply:rows.length?`جلسه‌های ثبت‌شده در این دستیار:\n${rows.map(m=>`${label(m)}${m.status==='cancelled'?' — لغوشده':''}`).join('\n')}`:'جلسه‌ای با این شرایط در فهرست این دستیار نیست.',meetings:rows.filter(m=>m.status==='active')};
 }
 if(p.intent==='notes'){
  const matches=meetings.filter(m=>Array.isArray(p.ids)&&p.ids.includes(m.id));
  if(matches.length!==1)return {reply:`صورت‌جلسهٔ کدام جلسه را نشان بدهم؟\n${meetings.map(label).join('\n')}`};
  const m=matches[0];if(!m.notes)return {reply:`هنوز صورت‌جلسه‌ای برای ${label(m)} ثبت نشده؛ از «صورت‌جلسه و کارها» در فهرست جلسه‌ها می‌توانی آن را بنویسی.`};
  return {reply:`صورت‌جلسهٔ ${label(m)}\n${m.notes.decisions||'تصمیمی ثبت نشده است.'}\n${m.notes.items.map(t=>`${t.done?'✓':'○'} ${t.title} — ${t.owner}${t.dueDate?' — موعد '+t.dueDate:''}`).join('\n')}`};
 }
 if(p.intent==='cancel'){
  const targets=p.scope==='all'?active:selected;
  if(!active.length)return {reply:'جلسهٔ فعالی در فهرست این دستیار نداری که لغو کنم. اتاق‌های قدیمی که بیرون از این فهرست ساخته شده‌اند باید در Talk بررسی شوند.'};
  if(!targets.length)return {reply:`کدام جلسه را لغو کنم؟\n${active.map(label).join('\n')}`};
  return {reply:`این ${targets.length.toLocaleString('fa-IR')} جلسه برای لغو انتخاب شده‌اند:\n${targets.map(label).join('\n')}\nبا تأیید زیر، رویدادهای تقویم و اتاق‌های Talk همراه تاریخچهٔ آن‌ها حذف می‌شوند. هنوز چیزی لغو نشده است.`,proposal:{kind:'cancel',meetings:targets} as Proposal};
 }
 if(p.intent==='reschedule'){
  if(selected.length!==1)return {reply:active.length?`کدام جلسه را به چه تاریخ و ساعتی منتقل کنم؟\n${active.map(label).join('\n')}`:'جلسهٔ فعالی در فهرست این دستیار نیست که زمانش را تغییر دهم.'};
  const m=selected[0];const d={...m.draft,date:p.draft?.date,time:p.draft?.time};
  if(!draftValid(d))return {reply:`زمان جدید ${label(m)} چه تاریخ و ساعتی باشد؟`};
  return {reply:`زمان ${label(m)} به ${d.date} ساعت ${d.time} تغییر کند؟ بعد از تأیید، تداخل تقویم بررسی می‌شود. هنوز تغییری انجام نشده است.`,proposal:{kind:'reschedule',meetings:[m],draft:d} as Proposal};
 }
 if(p.intent==='availability'){
  return draftValid(p.draft)?{reply:'تقویم شرکت‌کننده‌های انتخاب‌شده را برای این زمان بررسی می‌کنم.',draft:p.draft,checkAvailability:true}:{reply:'برای بررسی زمان آزاد، تاریخ و ساعت را مشخص کن و افراد را از فهرست شرکت‌کننده‌ها انتخاب کن.'};
 }
 if(p.intent==='prepare'&&draftValid(p.draft))return {reply:`پیش‌نویس «${p.draft.title}» برای ${p.draft.date} ساعت ${p.draft.time} آماده است. هنوز جلسه‌ای ساخته نشده؛ با تأیید زیر تقویم را بررسی و لینک واقعی را می‌سازم.`,draft:p.draft,requiresConfirmation:true};
 const reply=typeof p.reply==='string'?p.reply.trim().slice(0,3000):'';
 // Execution results are generated by the server after a real tool call, never by model prose.
 if(!reply||/(ساخته|لغو|حذف|ارسال|تغییر|منتقل|ثبت).{0,30}(شد|کردم|دادم|دادیم)|https?:\/\//.test(reply))return {reply:'می‌توانم جلسه آماده کنم، جلسه‌های ثبت‌شده را نشان دهم، تقویم را بررسی کنم یا برای لغو و تغییر زمان از تو تأیید بگیرم. چه کاری انجام بدهم؟'};
 return {reply};
}
